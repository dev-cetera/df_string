import 'dart:math';

import 'package:df_string/df_string.dart';
import 'package:test/test.dart';

/// Pins the case converters' output on ASCII input, byte for byte.
///
/// Code generators downstream turn field and column names into identifiers
/// with these converters, so any change to their ASCII output silently
/// renames generated code. The golden table below was recorded from 0.4.0,
/// the last ASCII-only implementation; the fuzz test compares the converters
/// against a frozen copy of that implementation on random ASCII strings.
void main() {
  group('Case conversions — ASCII output is pinned to 0.4.0', () {
    for (final row in _golden) {
      test('golden: ${row[0].replaceAll('\n', r'\n').replaceAll('\t', r'\t')}',
          () {
        expect(_convertAll(row[0]), equals(row.sublist(1)));
      });
    }

    test('fuzz: random ASCII strings match the frozen 0.4.0 implementation',
        () {
      final random = Random(20261021);
      const alphabet = 'abcxyzABCXYZ0189 _-./\$#!@\t\n';
      final printable = String.fromCharCodes(
        List.generate(95, (i) => i + 32),
      );
      for (var i = 0; i < 5000; i++) {
        final pool = i.isEven ? alphabet : printable;
        final length = random.nextInt(16);
        final input = String.fromCharCodes(
          List.generate(
            length,
            (_) => pool.codeUnitAt(random.nextInt(pool.length)),
          ),
        );
        expect(
          _convertAll(input),
          equals(_legacyConvertAll(input)),
          reason: 'input: ${input.codeUnits}',
        );
      }
    });
  });
}

// ░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░

List<String> _convertAll(String s) => [
      s.toSnakeCase(),
      s.toUpperSnakeCase(),
      s.toKebabCase(),
      s.toUpperKebabCase(),
      s.toCapitalizedKebabCase(),
      s.toDotCase(),
      s.toUpperDotCase(),
      s.toPathCase(),
      s.toCamelCase(),
      s.toPascalCase(),
      s.capitalize(),
      s.withFirstLetterAsLowerCase(),
      s.withCapitalizedWords(),
    ];

// ░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░░

/// A frozen copy of the 0.4.0 (ASCII-only) implementation. Do not edit.
List<String> _legacyConvertAll(String s) {
  final c = _legacyComponents(s);
  String cap(String e) => e.isEmpty ? e : e[0].toUpperCase() + e.substring(1);
  String low(String e) => e.isEmpty ? e : e[0].toLowerCase() + e.substring(1);
  final pascal = c.map(cap).join();
  final words = s.trim().isEmpty
      ? ''
      : s
          .trim()
          .split(RegExp(r'[\s-_]+'))
          .where((e) => e.isNotEmpty)
          .map((e) => cap(e.toLowerCase()))
          .join(' ');
  return [
    c.join('_'),
    c.join('_').toUpperCase(),
    c.join('-'),
    c.join('-').toUpperCase(),
    c.map(cap).join('-'),
    c.join('.'),
    c.join('.').toUpperCase(),
    c.join('/'),
    low(pascal),
    pascal,
    cap(s),
    low(s),
    words,
  ];
}

List<String> _legacyComponents(String s) {
  if (s.trim().isEmpty) return [];
  return s
      .trim()
      .replaceAllMapped(RegExp(r'([a-z0-9])([A-Z])'), (m) => '${m[1]} ${m[2]}')
      .replaceAllMapped(
        RegExp(r'([A-Z])([A-Z][a-z])'),
        (m) => '${m[1]} ${m[2]}',
      )
      .replaceAll(RegExp(r'[^a-zA-Z0-9]+'), ' ')
      .split(' ')
      .where((s) => s.isNotEmpty)
      .map((s) => s.toLowerCase())
      .toList();
}

